export const LEGAL_DOCUMENTS: LegalDocument[] = [PRIVACY_POLICY, TERMS_OF_USE];

/** Путь из адресной строки → документ. Возвращает null для любого другого адреса. */
export function readLegalDocument(pathname: string): LegalDocument | null {
  const normalized = pathname.replace(/\/+$/, "") || "/";
  return LEGAL_DOCUMENTS.find((document) => document.path === normalized) ?? null;
}

/*
 * Цветные подложки под инициалы друга, когда он не поставил фото.
 *
 * Подложка не случайная: цвет считается из id друга, поэтому один и тот же
 * человек всегда одного цвета — и в карточке места, и в списке друзей, и в
 * уведомлениях. Случайный цвет менялся бы при каждой перерисовке.
 *
 * Градиенты у тёплых и зелёных оттенков взяты на ступень темнее «просящейся»
 * яркости: белые инициалы 14px на обычном оранжевом дают ~3:1 и плохо читаются
 * на солнце. В текущем виде все двенадцать дают не меньше 4.5:1 по середине
 * градиента — текст лежит в центре круга, а не в светлом углу.
 */

export const AVATAR_GRADIENTS = [
  ["#f43f5e", "#be123c"], // малина
  ["#fb7185", "#9f1239"], // закат
  ["#ea580c", "#9a3412"], // мандарин
  ["#d97706", "#92400e"], // янтарь
  ["#65a30d", "#3f6212"], // олива
  ["#059669", "#065f46"], // изумруд
  ["#0d9488", "#115e59"], // бирюза
  ["#0891b2", "#155e75"], // лагуна
  ["#0284c7", "#075985"], // небо
  ["#6366f1", "#4338ca"], // индиго
  ["#8b5cf6", "#6d28d9"], // фиалка
  ["#d946ef", "#a21caf"], // фуксия
] as const;

/** Стабильный хэш строки: один и тот же id всегда даёт один и тот же цвет. */
function hashId(id: string): number {
  let hash = 0;
  for (let i = 0; i < id.length; i += 1) {
    hash = (hash * 31 + id.charCodeAt(i)) | 0;
  }
  return Math.abs(hash);
}

export function avatarGradient(id: string): string {
  const [from, to] = AVATAR_GRADIENTS[hashId(id) % AVATAR_GRADIENTS.length];
  return `linear-gradient(135deg, ${from}, ${to})`;
}

export function avatarInitials(name: string): string {
  return name
    .split(" ")
    .filter(Boolean)
    .map((part) => part[0])
    .slice(0, 2)
    .join("")
    .toUpperCase();
}

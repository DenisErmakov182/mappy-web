// Ссылка «Маршрут» до места во внешней карте — свой навигатор не строим
// (см. обсуждение), просто передаём точку зрелому приложению.

/**
 * Универсальная https-ссылка на Apple Maps с пешим маршрутом. На iOS
 * Safari/PWA такая ссылка открывает нативное приложение Карты сразу с
 * маршрутом от текущей позиции устройства — разрешение на геолокацию
 * спрашивает само приложение Карт, нам для этого ничего знать не нужно.
 * На платформах без Apple Maps ссылка откроется как обычная веб-страница
 * maps.apple.com. Целимся в iOS в первую очередь: PWA распространяется
 * без App Store именно туда, там же основная аудитория (см. ADR-001).
 */
export function buildWalkingDirectionsUrl(lat: number, lng: number): string {
  const params = new URLSearchParams({
    daddr: `${lat},${lng}`,
    dirflg: "w",
  });
  return `https://maps.apple.com/?${params.toString()}`;
}

import photoPlaceholderIcon from "../assets/illustrations/photo-placeholder.webp";

/*
 * Заглушка на месте фотографии.
 *
 * Подменяет саму фотографию, а не карточку целиком — это следует из макета
 * `2140:3055`, где заглушка показана и в списке, и с аватаром друга поверх неё.
 * Поэтому компонент не знает ничего о контексте: он просто занимает всё
 * доступное место, а рамки, скругления и накладки остаются на вызывающем.
 *
 * Два размера:
 *   - крупный (нода `2140:1184`) — иконка 80×80, отступ 6, заголовок и подпись;
 *   - компактный (нода `2140:3053` — карточка 187×132, иконка 53×53) — **только
 *     иконка**, без заголовка и подписи. В самом узле `2140:3053` подпись
 *     «Нет фото» под иконкой есть, но решение владельца 08.08.2026: в тесной
 *     карточке (список «Сохранённое», список мест друга, карусель под пином)
 *     текст убран — остаётся голая иконка.
 *
 * Про фон иконки. Первый экспорт через `get_design_context` (растровая
 * заливка компонента, отрендеренная в контексте карточки) пришёл с запечённым
 * фоном #f5f5f5 — на поверхности `--mappy-surface-secondary` (#f3f4f6) был
 * виден светлый квадрат вокруг тени. Источник самого узла оказался прозрачным:
 * `get_screenshot`/сырая заливка ноды `I2156:12403;2156:12381` отдают PNG
 * с альфа-каналом, фон не запечён в дизайне. Текущий ассет — обрезка этого
 * PNG по границе непрозрачных пикселей (с небольшим отступом под мягкий край
 * тени), пересжатая в lossy WebP с сохранением альфы. Правки в самом
 * Figma-файле не понадобилось.
 */
export function PhotoPlaceholder({ compact = false }: { compact?: boolean }) {
  return (
    <div className="flex h-full w-full flex-col items-center justify-center select-none">
      <img
        src={photoPlaceholderIcon}
        alt=""
        className={compact ? "h-[53px] w-[53px]" : "h-20 w-20"}
        draggable={false}
      />
      {!compact && (
        <>
          <p
            className="mt-1.5 text-[20px] leading-[28px] font-semibold"
            style={{ color: "var(--mappy-text-secondary)" }}
          >
            Нет фото
          </p>
          <p className="mt-1 text-[14px] leading-[18px]" style={{ color: "#99a1af" }}>
            С ним было бы лучше!
          </p>
        </>
      )}
    </div>
  );
}
